import {createRequire} from 'node:module';
const require=createRequire(process.env.SKIN_PLAYWRIGHT_ROOT+'/package.json');
const {chromium}=require('playwright');
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1600,height:1100}});
await page.goto('http://127.0.0.1:5188/skin-rebuild.html?mode=creation');
await page.waitForTimeout(4000);
await page.screenshot({path:process.argv[2],fullPage:true,timeout:180000});
console.log(await page.locator('#progress').innerText());
await browser.close();
